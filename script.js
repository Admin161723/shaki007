const PAGE_RE = /^(index|Hk|Man|news\d+)\.html(#.*)?$/;
async function navigate(url, push) {
    try {
        // Silence the playlist immediately, even if the news page takes time to load.
        if (NEWS_PATH.test(new URL(url, location.href).pathname)) syncNewsMusic(true);
        const r = await fetch(url);
        if (!r.ok) throw new Error('nf');
        const doc = new DOMParser().parseFromString(await r.text(), 'text/html');
        const scriptEl = document.querySelector('body > script');
        [...document.body.children].forEach(el => { if (el.tagName !== 'AUDIO' && el.tagName !== 'SCRIPT') el.remove(); });
        [...doc.body.children].forEach(el => {
            if (el.tagName === 'AUDIO' || el.tagName === 'SCRIPT') return;
            document.body.insertBefore(document.importNode(el, true), scriptEl);
        });
        document.title = doc.title;
        if (push) history.pushState({}, '', url);
        window.scrollTo(0, 0);
        initPage();
    } catch (e) { location.href = url; }
}
