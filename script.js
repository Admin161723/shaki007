const displayNamesCache = {};
function countryName(code, lang) {
    try {
        if (!displayNamesCache[lang]) displayNamesCache[lang] = new Intl.DisplayNames([intlLocale[lang]], { type: 'region' });
        return displayNamesCache[lang].of(code) || code;
    } catch (e) { return code; }
}
function flagOf(code) {
    return String.fromCodePoint(...[...code].map(c => 127397 + c.charCodeAt(0)));
}

function hashText(s) { let h = 5381; for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) | 0; return h; }

function chunkText(text, max) {
    const sentences = text.split(/(?<=[.!؟?])\s+/);
    const parts = []; let cur = "";
    sentences.forEach(s => {
        if ((cur + " " + s).length > max && cur) { parts.push(cur); cur = s; }
        else cur = cur ? cur + " " + s : s;
    });
    if (cur) parts.push(cur);
    return parts;
}

async function autoTranslate(text, lang) {
    const key = 'tr_' + lang + '_' + hashText(text);
    try { const c = localStorage.getItem(key); if (c) return c; } catch (e) {}
    try {
        const out = [];
        for (const p of chunkText(text, 450)) {
            const r = await fetch('https://api.mymemory.translated.net/get?q=' + encodeURIComponent(p) + '&langpair=fa|' + apiLang[lang]);
            const j = await r.json();
            out.push(j.responseData.translatedText);
        }
        const res = out.join(' ');
        try { localStorage.setItem(key, res); } catch (e) {}
        return res;
    } catch (e) { return text; }
}

function translateEl(el, lang) {
    if (el.dataset.orig === undefined) el.dataset.orig = el.textContent.trim();
    const key = el.dataset.i18n;
    const word = key && translations[lang] && translations[lang][key];
    if (word) { el.textContent = word; return; }
    if (lang === 'fa') { el.textContent = el.dataset.orig; return; }
    autoTranslate(el.dataset.orig, lang).then(t => { if (currentLang === lang) el.textContent = t; });
}

