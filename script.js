// Hold the playlist only on an open news article, not the muted news-list thumbnails.
let heldMusic = null;
function newsPlayerOpen() { return !!document.querySelector('.news-article audio, .news-article video'); }
function playingIndex() { return tracks.findIndex(a => !a.paused); }

function playTrack(i, t) {
    if (newsPlayerOpen()) {
        if (!heldMusic) heldMusic = { i, t };
        return Promise.resolve();
    }
    const a = tracks[i];
    if (t) {
        if (a.readyState >= 1) { try { a.currentTime = t; } catch (e) {} }
        else a.addEventListener('loadedmetadata', () => { try { a.currentTime = t; } catch (e) {} }, { once: true });
    }
    return a.play();
}

tracks.forEach((a, i) => a.addEventListener('ended', () => { playTrack((i + 1) % tracks.length, 0).catch(() => {}); }));

function saveMusicState() {
    const i = playingIndex();
    if (i < 0) return;
    try { localStorage.setItem('music_state', JSON.stringify({ i, t: tracks[i].currentTime })); } catch (e) {}
}
setInterval(saveMusicState, 1000);
window.addEventListener('pagehide', saveMusicState);

function resumeMusic() {
    if (playingIndex() >= 0) return Promise.resolve();
    let st = heldMusic;
    if (!st) {
        try { st = JSON.parse(localStorage.getItem('music_state')); } catch (e) {}
    }
    const i = st && typeof st.i === 'number' && tracks[st.i] ? st.i : 0;
    return playTrack(i, st && st.t ? st.t : 0);
}

function startMusic() {
    resumeMusic().then(() => {
        if (playingIndex() < 0) return;
        heldMusic = null;
        document.removeEventListener('click', startMusic);
        document.removeEventListener('touchstart', startMusic);
    }).catch(() => {});
}
function armMusicStart() {
    document.addEventListener('click', startMusic);
    document.addEventListener('touchstart', startMusic);
}
armMusicStart();
window.addEventListener('load', () => { try { if (localStorage.getItem('music_state')) startMusic(); } catch (e) {} });

function syncNewsMusic() {
    if (newsPlayerOpen()) {
        const i = playingIndex();
        if (i < 0) return;
        heldMusic = { i, t: tracks[i].currentTime };
        saveMusicState();
        tracks.forEach(a => { if (!a.paused) a.pause(); });
    } else if (heldMusic) {
        armMusicStart(); // Keep a gesture fallback if the browser blocks resuming.
        startMusic();
    }
}

const PAGE_RE = /^(index|Hk|Man|news\d+)\.html(#.*)?$/;
async function navigate(url, push) {
    try {
        const r = await fetch(url);
        if (!r.ok) throw new Error('nf');
        const doc = new DOMParser().parseFromString(await r.text(), 'text/html');
        const scriptEl = document.querySelector('body > script');
        [...document.body.children].forEach(el => { if (el.tagName !== 'AUDIO' && el.tagName !== 'SCRIPT') el.remove(); });
        [...doc.body.children].forEach(el => {
            if (el.tagName === 'AUDIO' || el.tagName === 'SCRIPT') return;
            document.body.insertBefore(document.importNode(el, true), scriptEl);
        });
        document.title = doc.title;
        if (push) history.pushState({}, '', url);
        window.scrollTo(0, 0);
        initPage();
    } catch (e) { location.href = url; }
}
document.addEventListener('click', e => {
    const a = e.target.closest && e.target.closest('a');
    if (!a || a.target === '_blank') return;
    const href = a.getAttribute('href') || '';
    if (PAGE_RE.test(href) && !e.ctrlKey && !e.metaKey && !e.shiftKey) { e.preventDefault(); navigate(href, true); }
});
window.addEventListener('popstate', () => navigate((location.pathname.split('/').pop() || 'index.html'), false));

