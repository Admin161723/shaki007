let heldMusic = null;
const mutedByNews = new Set();
function musicBlocked() { return inNews || heldByOtherNewsTab; }
function playingIndex() { return tracks.findIndex(a => !a.paused); }

function playTrack(i, t) {
    if (musicBlocked()) {
        if (!heldMusic) heldMusic = { i, t };
        return Promise.resolve();
    }
    const a = tracks[i];
    if (t) {
        if (a.readyState >= 1) { try { a.currentTime = t; } catch (e) {} }
        else a.addEventListener('loadedmetadata', () => { try { a.currentTime = t; } catch (e) {} }, { once: true });
    }
    return a.play();
}

tracks.forEach((a, i) => a.addEventListener('ended', () => { playTrack((i + 1) % tracks.length, 0).catch(() => {}); }));

function saveMusicState() {
    const i = playingIndex();
    if (i < 0) return;
    try { localStorage.setItem('music_state', JSON.stringify({ i, t: tracks[i].currentTime })); } catch (e) {}
}
setInterval(saveMusicState, 1000);
window.addEventListener('pagehide', saveMusicState);

function resumeMusic() {
    if (playingIndex() >= 0) return Promise.resolve();
    let st = heldMusic;
    if (!st) {
        try { st = JSON.parse(localStorage.getItem('music_state')); } catch (e) {}
    }
    const i = st && typeof st.i === 'number' && tracks[st.i] ? st.i : 0;
    return playTrack(i, st && st.t ? st.t : 0);
}

function startMusic(event) {
    // Don't start a song on the touch/click that takes the visitor into the news.
    const link = event && event.target.closest && event.target.closest('a[href]');
    if (link && link.origin === location.origin && NEWS_PATH.test(link.pathname)) return;
    resumeMusic().then(() => {
        if (musicBlocked() || playingIndex() < 0) return;
        heldMusic = null;
        document.removeEventListener('click', startMusic);
        document.removeEventListener('touchstart', startMusic);
    }).catch(() => {});
}
function armMusicStart() {
    document.addEventListener('click', startMusic);
    document.addEventListener('touchstart', startMusic);
}
